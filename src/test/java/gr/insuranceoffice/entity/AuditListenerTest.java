	// The database would cascade to ownership and policy on its own, but
	// nothing would be logged and the rows could not be put back. Loaded
	// first, as the services do before deleting.
	@Test
	void logsThePoliciesAndOwnershipsOfADeletedVehicle() {
		InsuredVehicle insured = insuredVehicle();
		Map<String, List<String>> before = rows("vehicle", "ownership", "policy");

		vehicleRepository.delete(vehicleRepository.findById(insured.vehicle().getId()).orElseThrow());

		assertThat(log()).filteredOn(row -> row.action().equals("DELETE"))
				.extracting(LogRow::entityType, LogRow::entityId)
				.containsExactlyInAnyOrder(
						tuple("Vehicle", insured.vehicle().getId()),
						tuple("Ownership", insured.primaryOwnership().getId()),
						tuple("Ownership", insured.coOwnership().getId()),
						tuple("Policy", insured.expiredPolicy().getId()),
						tuple("Policy", insured.currentPolicy().getId()));
		assertThat(rows("vehicle", "ownership", "policy")).allSatisfy((table, rows) -> assertThat(rows).isEmpty());

		restoreDeleted("Vehicle", "vehicle");
		restoreDeleted("Ownership", "ownership");
		restoreDeleted("Policy", "policy");

		assertThat(rows("vehicle", "ownership", "policy")).isEqualTo(before);
	}

	@Test
	void logsTheOwnershipsOfADeletedCustomer() {
		InsuredVehicle insured = insuredVehicle();
		Customer owner = insured.primaryOwnership().getCustomer();
		Vehicle secondVehicle = vehicleRepository.save(vehicle("WVWZZZ1KZAW654321", "ΚΜΝ-4321"));
		Ownership secondOwnership = ownershipRepository.save(ownership(secondVehicle, owner, "100", true));
		Map<String, List<String>> before = rows("customer", "ownership");

		customerRepository.delete(customerRepository.findById(owner.getId()).orElseThrow());

		assertThat(log()).filteredOn(row -> row.action().equals("DELETE"))
				.extracting(LogRow::entityType, LogRow::entityId)
				.containsExactlyInAnyOrder(
						tuple("Customer", owner.getId()),
						tuple("Ownership", insured.primaryOwnership().getId()),
						tuple("Ownership", secondOwnership.getId()));
		// The co-owner and the vehicles are not the deleted customer's.
		assertThat(ownershipRepository.findAll()).extracting(Ownership::getId)
				.containsExactly(insured.coOwnership().getId());
		assertThat(vehicleRepository.count()).isEqualTo(2);

		restoreDeleted("Customer", "customer");
		restoreDeleted("Ownership", "ownership");

		assertThat(rows("customer", "ownership")).isEqualTo(before);
	}

	// The copy returned by save() still has the empty child lists it was
	// created with. Deleting from it must fail rather than let the database
	// drop the children unlogged.
	@Test
	void refusesToDeleteFromACopyThatDoesNotKnowItsChildren() {
		InsuredVehicle insured = insuredVehicle();
		Map<String, List<String>> before = rows("vehicle", "ownership", "policy");

		assertThatThrownBy(() -> vehicleRepository.delete(insured.vehicle()))
				.isInstanceOf(DataAccessException.class);

		assertThat(rows("vehicle", "ownership", "policy")).isEqualTo(before);
		assertThat(log()).extracting(LogRow::action).containsOnly("CREATE");
	}

	// Task 10: the change is logged against whoever is logged in
