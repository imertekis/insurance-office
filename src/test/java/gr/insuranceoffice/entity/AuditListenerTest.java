	@Test
	void logsPolicyInsertUpdateAndDelete() {
		Intermediary intermediary = intermediaryRepository.save(intermediary("Παπαδόπουλος Νίκος"));
		Vehicle vehicle = vehicleRepository.save(vehicle("WVWZZZ1KZAW123456", "ΑΒΕ-1234"));
		Policy policy = policyRepository.save(policy(vehicle, "2100000001", LocalDate.of(2026, 3, 1)));
		policy.setIntermediary(intermediary);
		Policy saved = policyRepository.save(policy);

		// Read back as the database holds it: 120.00. Retyping the amount as
		// 120 is not a change; the new end date is.
		Policy reloaded = policyRepository.findById(saved.getId()).orElseThrow();
		reloaded.setPremium(new BigDecimal("120"));
		reloaded.setEndDate(LocalDate.of(2026, 9, 1));
		reloaded = policyRepository.save(reloaded);
		policyRepository.delete(reloaded);

		List<LogRow> log = log().stream().filter(row -> row.entityType().equals("Policy")).toList();
		assertThat(log).extracting(LogRow::action).containsExactly("CREATE", "UPDATE", "UPDATE", "DELETE");
		assertThat(log).extracting(LogRow::entityId).containsOnly(saved.getId());

		assertThat(log.get(0).newValues()).contains(entry("policy_number", "2100000001"),
				entry("vehicle_id", vehicle.getId().intValue()), entry("intermediary_id", null),
				entry("start_date", "2026-03-01"), entry("end_date", "2027-03-01"), entry("surcharge", false));
		assertThat(log.get(1).oldValues()).containsExactly(entry("intermediary_id", null));
		assertThat(log.get(1).newValues()).containsExactly(entry("intermediary_id", intermediary.getId().intValue()));
		assertThat(log.get(2).oldValues()).containsExactly(entry("end_date", "2027-03-01"));
		assertThat(log.get(2).newValues()).containsExactly(entry("end_date", "2026-09-01"));
		assertThat(log.get(3).oldValues()).contains(entry("policy_number", "2100000001"),
				entry("intermediary_id", intermediary.getId().intValue()), entry("end_date", "2026-09-01"));
		assertThat(log.get(3).newValues()).isNull();
	}

