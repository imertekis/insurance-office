	@Test
	void logsCustomerInsertUpdateAndDelete() {
		Customer customer = customerRepository.save(customer("Αλεξίου", "Μαρία", "900000080"));
		customer.setMobile("6900000001");
		customer = customerRepository.save(customer);
		customerRepository.delete(customer);

		List<LogRow> log = log();
		assertThat(log).extracting(LogRow::action).containsExactly("CREATE", "UPDATE", "DELETE");
		assertThat(log).extracting(LogRow::entityType).containsOnly("Customer");
		assertThat(log).extracting(LogRow::entityId).containsOnly(customer.getId());

		LogRow created = log.get(0);
		assertThat(created.oldValues()).isNull();
		assertThat(created.newValues()).contains(entry("id", customer.getId().intValue()),
				entry("last_name", "Αλεξίου"), entry("first_name", "Μαρία"), entry("tax_id", "900000080"),
				entry("mobile", null));
		// Generated by the database, not part of the record.
		assertThat(created.newValues()).doesNotContainKey("search_normalized");

		// Only what changed.
		LogRow updated = log.get(1);
		assertThat(updated.oldValues()).containsExactly(entry("mobile", null));
		assertThat(updated.newValues()).containsExactly(entry("mobile", "6900000001"));

		LogRow deleted = log.get(2);
		assertThat(deleted.oldValues()).contains(entry("last_name", "Αλεξίου"), entry("mobile", "6900000001"));
		assertThat(deleted.newValues()).isNull();
	}

